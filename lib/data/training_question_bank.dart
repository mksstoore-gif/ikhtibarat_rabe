import 'models.dart';

class TrainingQuestionBank {
  static List<Question> build(List<LessonInfo> lessons) {
    final out=<Question>[];
    for(final lesson in lessons.where((l)=>l.subjectId!='math')){
      final facts=_factsFor(lesson);
      for(var i=0;i<facts.length;i++){
        out.addAll(_fromFact(lesson,facts[i],i));
      }
    }
    return out;
  }

  static List<Question> _fromFact(LessonInfo l,_Fact f,int index){
    final base=index*5;
    final options=<String>[f.answer,...f.distractors].toSet().toList();
    if(options.length>1){
      final shift=(index+l.id.length)%options.length;
      final rotated=<String>[...options.skip(shift),...options.take(shift)];
      options
        ..clear()
        ..addAll(rotated);
    }
    return [
      _q(l,base,QuestionType.trueFalse,f.truth,'صح',const ['صح','خطأ'],f.truth),
      _q(l,base+1,QuestionType.trueFalse,f.falsehood,'خطأ',const ['صح','خطأ'],'التصحيح: ' + f.truth),
      _q(l,base+2,QuestionType.multipleChoice,f.question,f.answer,options,f.truth),
      _q(l,base+3,QuestionType.multipleChoice,'أي العبارتين الآتيتين صحيحة؟',f.truth,[f.truth,f.falsehood],f.truth),
      _q(l,base+4,QuestionType.shortAnswer,f.question,f.answer,const [],f.truth),
    ];
  }

  static Question _q(LessonInfo l,int i,QuestionType type,String text,String answer,List<String> options,String explanation)=>Question(
    id:'${l.id}_train_$i',
    subjectId:l.subjectId,
    unitId:l.unitId,
    lessonId:l.id,
    skillId:'${l.id}_skill',
    type:type,
    difficulty:Difficulty.values[i%3],
    question:text,
    options:options,
    correctAnswer:answer,
    explanation:explanation,
    score:1,
    isOfficial:false,
  );

  static List<_Fact> _factsFor(LessonInfo l){
    return switch(l.subjectId){
      'arabic' => _arabic(l.name),
      'science' => _science(l.name),
      'social' => _social(l.name),
      'islamic' => _islamic(l.name),
      _ => const [],
    };
  }

